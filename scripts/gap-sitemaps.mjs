function locs(xml) {
  return [...xml.matchAll(/<loc>([^<]+)<\/loc>/gi)].map((m) => m[1]);
}

function covered(slug) {
  if (ignore.has(slug)) return { ok: true, reason: "ignore" };
  if (ours.has(slug)) return { ok: true, reason: "exact", mapped: slug };
  const hy = slug.replace(/_/g, "-");
  if (ours.has(hy)) return { ok: true, reason: "hyphen", mapped: hy };
  if (Object.prototype.hasOwnProperty.call(alias, slug)) {
    const mapped = alias[slug];
    if (mapped === null) return { ok: false, reason: "known-gap", mapped: null };
    if (mapped && ours.has(mapped))
      return { ok: true, reason: "alias", mapped };
    return { ok: false, reason: "bad-alias", mapped };
  }
  if (Object.prototype.hasOwnProperty.call(alias, hy)) {
    const mapped = alias[hy];
    if (mapped === null) return { ok: false, reason: "known-gap", mapped: null };
    if (mapped && ours.has(mapped))
      return { ok: true, reason: "alias", mapped };
    return { ok: false, reason: "bad-alias", mapped };
  }
  // Heuristic: looks like a tool if contains pdf / convert patterns
  const looksTool =
    /pdf|ocr|sign|merge|split|compress|rotate|watermark|crop|page|unlock|protect|scan|fax|form|edit|convert|word|excel|ppt|jpg|png|image|html|txt|csv|epub|tiff|heic|svg|redact|nup|booklet|annotate|flatten|metadata|password|extract|delete|organize|repair|grayscale|compare|translate|header|footer|bates|overlay|underlay|deskew|resize|impose|portfolio|attachment|invert|mirror|scale|whiteout|censur|stamp|background|validate|xfa|linearize|n-up|heic|epub|mobi|markdown|json|xml|zip|url-to|webpage|website/i.test(
      slug,
    );
  if (!looksTool) return { ok: true, reason: "non-tool" };
  return { ok: false, reason: "unmapped-tool" };
}

const report = { oursCount: ours.size, sites: {} };

for (const site of sites) {
  const xml = await (await fetch(site.url)).text();
  const set = new Set();
  for (const loc of locs(xml)) {
    try {
      const s = site.keep(loc);
      if (s) set.add(s);
    } catch {
      /* ignore bad urls */
    }
  }
  const missing = [];
  const coveredList = [];
  for (const s of [...set].sort()) {
    const c = covered(s);
    if (c.ok) coveredList.push({ slug: s, ...c });
    else missing.push({ slug: s, ...c });
  }
  report.sites[site.name] = {
    url: site.url,
    englishPaths: set.size,
    covered: coveredList.length,
    missingCount: missing.length,
    missing,
  };
  console.log(
    `\n=== ${site.name} english=${set.size} covered=${coveredList.length} missing=${missing.length}`,
  );
  for (const m of missing) console.log(`- ${m.slug} (${m.reason})`);
}

const unionMissing = new Map();
for (const site of Object.values(report.sites)) {
  for (const m of site.missing) {
    if (!unionMissing.has(m.slug))
      unionMissing.set(m.slug, { ...m, sites: [] });
    // sites filled below
  }
}
for (const [name, site] of Object.entries(report.sites)) {
  for (const m of site.missing) {
    unionMissing.get(m.slug).sites.push(name);
  }
}
report.unionMissing = [...unionMissing.values()].sort((a, b) =>
  a.slug.localeCompare(b.slug),
);

console.log(`\n=== UNION missing tools (${report.unionMissing.length})`);
for (const m of report.unionMissing) {
  console.log(`- ${m.slug} [${m.sites.join(", ")}] (${m.reason})`);
}

writeFileSync(
  new URL("./gap-sitemaps-report.json", import.meta.url),
  JSON.stringify(report, null, 2),
);
console.log("\nWrote scripts/gap-sitemaps-report.json");
